export type Key = keyof typeof en;
type Vars = Record<string, string | number>;

const dictionary: Record<Key, string> = en;
let numbers: Intl.NumberFormat;

/** Looks a string up and fills `{name}` placeholders. Numbers are formatted for the interface locale. */
export function t(key: Key, vars?: Vars): string {
  const text = dictionary[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = vars[name];
    return typeof value === 'number' ? (numbers ??= new Intl.NumberFormat('en')).format(value) : String(value ?? '');
  });
}

/** The interface locale: one place to change when a second dictionary lands. */
export const locale = 'en';

/** Human name of a summary language code ("cs" → "Czech"); the code itself when unknown. */
export function languageName(code: string | null | undefined): string {
  if (!code) return '';
  // STILLFEED_LANGUAGE is usually a name ("Czech"); only short tags like "cs" or "pt-BR" need translating.
  if (!/^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$/.test(code)) return code;
  try { return new Intl.DisplayNames([locale], { type: 'language' }).of(code) || code; } catch { return code; }
}
